
CREATE TABLE dim_categories (
    CategoryID INTEGER PRIMARY KEY,
    CategoryName VARCHAR(25) NOT NULL,
    Description VARCHAR(255)
);

CREATE TABLE dim_suppliers (
    SupplierID INTEGER PRIMARY KEY,
    SupplierName VARCHAR(50) NOT NULL,
    ContactName VARCHAR(50),
    Address VARCHAR(50),
    City VARCHAR(20),
    PostalCode VARCHAR(10),
    Country VARCHAR(15),
    Phone VARCHAR(15)
);

CREATE TABLE dim_products (
    ProductID INTEGER PRIMARY KEY,
    ProductName VARCHAR(50) NOT NULL,
    Unit VARCHAR(25),
    Price NUMERIC,
    CategoryID INTEGER NOT NULL,
    SupplierID INTEGER NOT NULL,
    CONSTRAINT fk_dim_products_categories FOREIGN KEY (CategoryID) REFERENCES dim_categories(CategoryID),
    CONSTRAINT fk_dim_products_suppliers FOREIGN KEY (SupplierID) REFERENCES dim_suppliers(SupplierID)
);

CREATE TABLE dim_customers (
    CustomerID INTEGER PRIMARY KEY,
    CustomerName VARCHAR(50) NOT NULL,
    ContactName VARCHAR(50),
    Address VARCHAR(50),
    City VARCHAR(20),
    PostalCode VARCHAR(10),
    Country VARCHAR(15)
);

CREATE TABLE dim_employees (
    EmployeeID INTEGER PRIMARY KEY,
    LastName VARCHAR(15) NOT NULL,
    FirstName VARCHAR(15) NOT NULL,
    BirthDate TIMESTAMP,
    Photo VARCHAR(25),
    Notes VARCHAR(1024)
);

CREATE TABLE dim_shippers (
    ShipperID INTEGER PRIMARY KEY,
    ShipperName VARCHAR(25) NOT NULL,
    Phone VARCHAR(15)
);

CREATE TABLE dim_date (
    DateID INTEGER PRIMARY KEY, -- Формат YYYYMMDD
    FullDate DATE NOT NULL,
    Day INTEGER NOT NULL,
    Month INTEGER NOT NULL,
    MonthName VARCHAR(15) NOT NULL,
    Quarter INTEGER NOT NULL,
    Year INTEGER NOT NULL
);

CREATE TABLE fact_sales (
    FactSalesID INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    OrderDetailID INTEGER UNIQUE, -- Унікальний ідентифікатор рядка з джерела
    OrderID INTEGER NOT NULL,     -- Degenerate dimension
    ProductID INTEGER NOT NULL,
    CustomerID INTEGER NOT NULL,
    EmployeeID INTEGER NOT NULL,
    ShipperID INTEGER NOT NULL,
    DateID INTEGER NOT NULL,
    Quantity INTEGER NOT NULL,
    UnitPrice NUMERIC NOT NULL,
    TotalAmount NUMERIC NOT NULL,
    
    CONSTRAINT fk_fact_sales_products FOREIGN KEY (ProductID) REFERENCES dim_products(ProductID),
    CONSTRAINT fk_fact_sales_customers FOREIGN KEY (CustomerID) REFERENCES dim_customers(CustomerID),
    CONSTRAINT fk_fact_sales_employees FOREIGN KEY (EmployeeID) REFERENCES dim_employees(EmployeeID),
    CONSTRAINT fk_fact_sales_shippers FOREIGN KEY (ShipperID) REFERENCES dim_shippers(ShipperID),
    CONSTRAINT fk_fact_sales_date FOREIGN KEY (DateID) REFERENCES dim_date(DateID)
);


INSERT INTO dim_categories (CategoryID, CategoryName, Description)
SELECT CategoryID, CategoryName, Description FROM Categories;

INSERT INTO dim_suppliers (SupplierID, SupplierName, ContactName, Address, City, PostalCode, Country, Phone)
SELECT SupplierID, SupplierName, ContactName, Address, City, PostalCode, Country, Phone FROM Suppliers;


INSERT INTO dim_products (ProductID, ProductName, Unit, Price, CategoryID, SupplierID)
SELECT ProductID, ProductName, Unit, Price, CategoryID, SupplierID FROM Products;

INSERT INTO dim_customers (CustomerID, CustomerName, ContactName, Address, City, PostalCode, Country)
SELECT CustomerID, CustomerName, ContactName, Address, City, PostalCode, Country FROM Customers;

INSERT INTO dim_employees (EmployeeID, LastName, FirstName, BirthDate, Photo, Notes)
SELECT EmployeeID, LastName, FirstName, BirthDate, Photo, Notes FROM Employees;

INSERT INTO dim_shippers (ShipperID, ShipperName, Phone)
SELECT ShipperID, ShipperName, Phone FROM Shippers;



INSERT INTO dim_date (DateID, FullDate, Day, Month, MonthName, Quarter, Year)
SELECT DISTINCT
    CAST(TO_CHAR(OrderDate, 'YYYYMMDD') AS INTEGER) AS DateID,
    CAST(OrderDate AS DATE) AS FullDate,
    EXTRACT(DAY FROM OrderDate) AS Day,
    EXTRACT(MONTH FROM OrderDate) AS Month,
    TO_CHAR(OrderDate, 'Month') AS MonthName,
    EXTRACT(QUARTER FROM OrderDate) AS Quarter,
    EXTRACT(YEAR FROM OrderDate) AS Year
FROM Orders;














INSERT INTO fact_sales (OrderDetailID, OrderID, ProductID, CustomerID, EmployeeID, ShipperID, DateID, Quantity, UnitPrice, TotalAmount)
SELECT 
    od.OrderDetailID,
    od.OrderID,
    od.ProductID,
    o.CustomerID,
    o.EmployeeID,
    o.ShipperID,
    CAST(TO_CHAR(o.OrderDate, 'YYYYMMDD') AS INTEGER) AS DateID,
    od.Quantity,
    p.Price AS UnitPrice,
    (od.Quantity * p.Price) AS TotalAmount
FROM OrderDetails od
JOIN Orders o ON od.OrderID = o.OrderID
JOIN Products p ON od.ProductID = p.ProductID;